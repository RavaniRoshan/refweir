#!/usr/bin/env bash
# Reset the hosted Refweir demo to a clean, seeded state.
#
# This is destructive: it removes the demo data volume, bootstraps a fresh
# instance, starts the stack, and runs seed.sh. Schedule it with the systemd
# units in ./systemd/ or a cron entry.
#
# Usage: deploy/demo/reset.sh
# Env:   DEMO_PORT (default 8088), RESET_SKIP_BUILD=1 to reuse the image.

set -euo pipefail

DEMO_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
cd "$DEMO_DIR"

if ! command -v docker >/dev/null 2>&1; then
    echo "error: docker is required" >&2
    exit 1
fi

if [ ! -f .env ]; then
    umask 077
    if command -v openssl >/dev/null 2>&1; then
        secret="$(openssl rand -hex 32)"
    else
        secret="$(head -c 48 /dev/urandom | base64 | tr -d '\n=+/' | cut -c1-48)"
    fi
    {
        echo "# Generated by deploy/demo/reset.sh. Do not commit."
        echo "REFWEIR_JWT_SECRET=$secret"
        echo "DEMO_PORT=${DEMO_PORT:-8088}"
        echo "DEMO_PUBLIC_URL=${DEMO_PUBLIC_URL:-http://localhost:${DEMO_PORT:-8088}}"
        echo "DEMO_GIT_URL=${DEMO_GIT_URL:-localhost:${DEMO_PORT:-8088}}"
    } >.env
    echo "==> wrote deploy/demo/.env (secret generated)"
fi

# Load the generated values for the seed step.
set -a
# shellcheck disable=SC1091
. ./.env
set +a

echo "==> removing the demo stack and data volume"
docker compose down -v --remove-orphans

BOOTSTRAP_LOG="$(mktemp "${TMPDIR:-/tmp}/refweir-demo-bootstrap.XXXXXX")"
trap 'rm -f "$BOOTSTRAP_LOG"' EXIT

echo "==> bootstrapping a fresh demo instance"
if ! docker compose run --rm --no-deps \
    -e REFWEIR_TELEMETRY_OPT_IN=0 \
    refweird bootstrap \
    --email demo-admin@refweir.dev \
    --namespace demo \
    --data-dir /var/lib/refweir >"$BOOTSTRAP_LOG" 2>&1; then
    echo "error: bootstrap failed" >&2
    cat "$BOOTSTRAP_LOG" >&2
    exit 1
fi

API_KEY="$(awk '/^API Key:/ {print $3; exit}' "$BOOTSTRAP_LOG")"
if [ -z "$API_KEY" ]; then
    echo "error: could not parse the bootstrap API key" >&2
    cat "$BOOTSTRAP_LOG" >&2
    exit 1
fi

echo "==> starting the demo stack"
if [ "${RESET_SKIP_BUILD:-0}" = "1" ]; then
    docker compose up -d
else
    docker compose up -d --build
fi

echo "==> seeding the demo"
"$DEMO_DIR/seed.sh" "http://127.0.0.1:${DEMO_PORT:-8088}" "$API_KEY"

echo "==> demo reset complete"
echo "    public URL: ${DEMO_PUBLIC_URL:-http://localhost:${DEMO_PORT:-8088}}"
echo "    reset next: schedule deploy/demo/reset.sh (systemd timer or cron)"
